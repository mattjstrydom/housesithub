// Builds src/content.generated.js from the approved lesson scripts (Course Rebuild/Scripts/M*.md).
// Run (from the lms folder): node scripts/build_content.mjs "path/to/Course Rebuild/Scripts"
// Transcripts are the spoken text only: tags, pause markers and VERIFY notes are removed.
// Wistia video ids live in src/wistia.json (lesson id -> Wistia media id), so you can add them without regenerating.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const scriptsDir = process.argv[2];
if (!scriptsDir) {
  console.error('Usage: node scripts/build_content.mjs "path/to/Course Rebuild/Scripts"');
  process.exit(1);
}
const files = fs.readdirSync(scriptsDir).filter((f) => /^M[1-5]_.*\.md$/.test(f)).sort();

const modules = [];
for (const f of files) {
  const text = fs.readFileSync(path.join(scriptsDir, f), "utf8");
  const mh = text.match(/^# Module (\d+): (.*?) \(\d+ lessons?\)/m);
  if (!mh) throw new Error("No module heading in " + f);
  const mod = { id: "m" + mh[1], n: Number(mh[1]), title: mh[2].trim(), lessons: [] };
  const parts = text.split(/^## (M\d) L(\d+): (.*?) \(about ([\d.]+) min, \d+ words\)$/m);
  for (let i = 1; i < parts.length; i += 5) {
    const n = Number(parts[i + 1]);
    const title = parts[i + 2].replace(/^NEW\.\s*/, "").trim();
    const minutes = Math.max(1, Math.round(Number(parts[i + 3])));
    const body = parts[i + 4].split(/^VERIFY:/m)[0];
    const paragraphs = [...body.matchAll(/^\[M\dL\d+_\w+ \| [^\]]+\] (.*)$/gm)].map((m) =>
      m[1].replace(/\[\[pause [0-9.]+\]\]/g, " ").replace(/\s+/g, " ").trim(),
    );
    if (!paragraphs.length) throw new Error(`No segments in ${mod.id} lesson ${n}`);
    mod.lessons.push({ id: `m${mh[1]}l${n}`, mod: mod.id, n, slug: "l" + n, title, minutes, paragraphs });
  }
  modules.push(mod);
}
const total = modules.reduce((a, m) => a + m.lessons.length, 0);
const out = `// GENERATED by scripts/build_content.mjs. Do not edit by hand.\nexport default ${JSON.stringify({ modules }, null, 1)};\n`;
fs.writeFileSync(path.join(here, "..", "src", "content.generated.js"), out);
console.log(`Wrote ${modules.length} modules, ${total} lessons`);
